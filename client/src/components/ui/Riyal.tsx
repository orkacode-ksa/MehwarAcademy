/** نص من الخادم (إشعار · قيد محفظة · عنوان طلب) يحمل «ر.س» ← يُعرض بالرمز. */
export function RiyalText({ text }: { text: string }) {
  const parts = text.split(/\s?ر\.س/);
  if (parts.length === 1) return <>{text}</>;
  return (
    <>
      {parts.map((p, i) => (
        <Fragment key={i}>
          {p}
          {i < parts.length - 1 && (
            <>
              {" "}
              <Riyal />
            </>
          )}
        </Fragment>
      ))}
    </>
  );
}
