import { Alert } from "../ui/Alert.js";

/**
 * بيان نطاق الصلاحية على كل شاشة قسم.
 * ليس تزييناً: عضو هيئة التدريس قُطع له وعد صريح على شاشته بأن مؤشر التزامه «لا
 * يُشارَك مع القسم ولا الكلية ولا أي جهة». إعلان الحدّ للطرفين هو ما يجعل الوعد
 * قابلاً للتحقق بدل أن يكون ادّعاءً.
 */
export function ScopeNotice({ className = "" }: { className?: string }) {
  return (
    <Alert tone="teal" icon="shield" title="نطاق صلاحيات هذه اللوحة" className={className}>
      عرض تجميعي للقراءة فقط. لا تصل إلى محتوى محاضرة، ولا إلى درجة طالب بعينه، ولا إلى كشف شعبة، ولا إلى مؤشر التزام أي عضو ولا تقييمه
      السنوي — لأن الثقة شرط لاستخدام الأعضاء للمنصة.
    </Alert>
  );
}
