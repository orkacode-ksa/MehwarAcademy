interface IconProps extends SVGProps<SVGSVGElement> {
  name: IconName;
  /** الحالة النشطة: أيقونة ممتلئة ثنائية اللون بدل الخطية */
  active?: boolean;
}

/** علامة مِحوَر — دائرتان متحدتا المركز ونقطة ذهبية؛ هوية المنتج فتبقى مرسومة يدويًا */
function LogoMark({ className, ...rest }: SVGProps<SVGSVGElement>) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.7}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
      {...rest}
    >
      <circle cx="12" cy="12" r="8.5" opacity=".45" />
      <circle cx="12" cy="12" r="4" />
      <circle cx="12" cy="3.5" r="1.6" fill="currentColor" stroke="none" />
    </svg>
  );
}

export function Icon({ name, className, active = false, strokeWidth = 1.6, ...rest }: IconProps) {
  if (name === "logo") return <LogoMark className={className} {...rest} />;
  const Cmp = (active ? DUOTONE : LINEAR)[name];
  return <Cmp className={className} strokeWidth={strokeWidth} aria-hidden="true" {...rest} />;
}
